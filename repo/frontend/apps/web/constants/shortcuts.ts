/** Widen optional contract fields for consumers while preserving inferred IDs. */
export const SHORTCUT_COMMANDS: readonly ShortcutCommandDefinition[] = SHORTCUT_COMMAND_DEFINITIONS;

const commandsById = new Map<string, ShortcutCommandDefinition>(
  SHORTCUT_COMMANDS.map((command) => [command.id, command]),
);

export function getCommandDefinition(commandId: string) {
  return commandsById.get(commandId);
}

