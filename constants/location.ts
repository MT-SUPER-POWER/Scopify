/**
 * 根据网易云返回的省份/城市代码，格式化输出地名
 */
export function getLocationName(provinceCode?: number, cityCode?: number): string | null {
  if (!provinceCode) return null;

  const province = PROVINCE_MAP[provinceCode];
  if (!province) return "其他地区";

  // 直辖市直接返回直辖市名称
  if ([110000, 120000, 310000, 500000].includes(provinceCode)) {
    return province;
  }

  if (cityCode && CITY_MAP[cityCode]) {
    const city = CITY_MAP[cityCode];
    // 如果城市和省份同名，仅显示省份
    if (city === province) return province;
    return `${province} ${city}`;
  }

  return province;
}
